function ensureCityOffers(cityId) {
  if (GENERATED_CITIES.has(cityId)) return;
  GENERATED_CITIES.add(cityId);
  const city = CITIES.find(c => c.id === cityId);
  if (!city) return;
  const citi = CITIES.indexOf(city);
  COMPONENTS.forEach((c, ci) => {
    const rnd = seededRand(1000 + ci * 137 + citi * 31);
    const storesHere = [...NEW_STORES].sort(() => rnd() - 0.5).slice(0, 2);
    storesHere.forEach(store => {
      const jitter = 0.97 + rnd() * 0.06;
      const price = Math.round(c.basePrice * store.coeff * city.coeff * jitter / 10) * 10;
      const oldPrice = rnd() > 0.6 ? Math.round(price * (1.08 + rnd() * 0.15) / 10) * 10 : null;
      const o = {
        componentId: c.id, storeId: store.id, regionId: city.id,
        price, oldPrice, condition: 'new',
        deliveryDays: city.id === 'online' ? 1 + Math.floor(rnd() * 5) : 0,
        deliveryPrice: city.id === 'online' ? (rnd() > 0.4 ? 0 : 290 + Math.floor(rnd() * 4) * 100) : 0,
        updated: `2026-11-${String(20 + Math.floor(rnd() * 6)).padStart(2,'0')}`,
      };
      OFFERS.push(o);
      const k = c.id + '|' + city.id;
      if (!OFFER_INDEX.has(k)) OFFER_INDEX.set(k, []);
      OFFER_INDEX.get(k).push(o);
    });
  });
  OFFER_INDEX.forEach(arr => arr.sort((a, b) => a.price - b.price));
}
