function normalize(s) { return String(s || '').toLowerCase().replace(/ё/g, 'е').trim(); }
function compSearchText(c) {
  const specs = Object.values(c.specs).join(' ');
  const cat = catById(c.cat);
  return normalize(c.name + ' ' + c.brand + ' ' + (cat ? cat.name : c.cat) + ' ' + specs + ' ' + (c.aliases || []).join(' '));
}
function matchesQuery(c, query) {
  const q = normalize(query);
  if (!q) return true;
  const text = compSearchText(c);
  // Алиасы категорий: если запрос содержит слово-категорию, проверяем категорию
  // и исключаем эти слова из токенов (иначе «видяха» не найдётся в названии)
  const aliasTokens = new Set();
  for (const a of SEARCH_ALIASES) {
    if (a.keys.some(k => q.includes(k))) {
      if (c.cat !== a.cat) return false;
      (a.generic || a.keys).forEach(k => aliasTokens.add(k));
    }
  }
  const tokens = q.split(/\s+/).filter(Boolean).filter(t => ![...aliasTokens].some(k => k.includes(t) || t.includes(k)));
  return tokens.every(t => text.includes(t));
}
function searchComponents(query, { cat = 'all', brand = 'all', minPriceV = null, maxPriceV = null, yearFilter = 'all', cityId = null } = {}) {
  let list = COMPONENTS.filter(c => matchesQuery(c, query));
  if (cat !== 'all') list = list.filter(c => c.cat === cat);
  if (brand !== 'all') list = list.filter(c => c.brand === brand);
  if (yearFilter === 'new') list = list.filter(c => c.year >= 2020);
  if (yearFilter === 'old') list = list.filter(c => c.year < 2020);
  if (minPriceV !== null || maxPriceV !== null) {
    list = list.filter(c => {
      const p = (cityId ? minPrice(c.id, cityId, 'new') : null) ?? c.basePrice;
      if (minPriceV !== null && p < minPriceV) return false;
      if (maxPriceV !== null && p > maxPriceV) return false;
      return true;
    });
  }
  return list;
}
