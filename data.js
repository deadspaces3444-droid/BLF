function estimateFps(cpuId, gpuId, ramId, gameId, res = '1080p', settings = 'ultra') {
  const cpu = byId(cpuId), gpu = byId(gpuId), ram = ramId ? byId(ramId) : null;
  const game = GAMES.find(g => g.id === gameId);
  if (!cpu || !gpu || !game) return 0;
  const gpuFactor = Math.pow(Math.max(gpu.perf, 5) / REF_GPU_PERF, game.gpuWeight);
  const cpuFactor = Math.pow(Math.max(cpu.perf, 5) / REF_CPU_PERF, 1 - game.gpuWeight);
  let fps = game.refFps * gpuFactor * cpuFactor;
  if (res === '1440p') fps *= game.res1440;
  else if (res === '4K') fps *= game.res4k;
  if (settings === 'medium') fps *= 1.45;
  if (ram && ram.specs.capacityGb < 16) fps *= 0.92;
  if (ram && ram.specs.capacityGb < 8) fps *= 0.85;
  return Math.max(1, Math.round(fps));
}
function estimateBuildFps(parts, gameId, res = '1080p', settings = 'ultra') {
  return estimateFps(parts.cpu, parts.gpu, parts.ram, gameId, res, settings);
}
